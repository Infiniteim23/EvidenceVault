package com.evidencevault.controller;

import com.evidencevault.entity.Evidence;
import com.evidencevault.entity.EvidenceVerification;
import com.evidencevault.service.EvidenceService;
import jakarta.servlet.http.HttpServletRequest;
import org.springframework.http.*;
import org.springframework.security.core.Authentication;
import org.springframework.stereotype.Controller;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestMapping;

import java.nio.charset.StandardCharsets;
import java.time.format.DateTimeFormatter;

@Controller
@RequestMapping("/reports")
public class ReportController {

    private final EvidenceService evidenceService;
    private final com.evidencevault.service.AuditService auditService;

    public ReportController(EvidenceService evidenceService, com.evidencevault.service.AuditService auditService) {
        this.evidenceService = evidenceService;
        this.auditService = auditService;
    }

    @GetMapping("/evidence/{id}")
    public ResponseEntity<byte[]> evidenceReport(
            @PathVariable Long id,
            Authentication authentication,
            HttpServletRequest request) {

        Evidence evidence = evidenceService.getAuthorized(id, authentication.getName(), request.getRemoteAddr(), "EVIDENCE_REPORT_VIEWED");
        var history = evidenceService.history(id);
        var timeline = auditService.forEntity("EVIDENCE", String.valueOf(id));
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

        StringBuilder report = new StringBuilder();
        report.append("EVIDENCEVAULT - DIGITAL EVIDENCE INTEGRITY REPORT\n");
        report.append("============================================================\n\n");
        report.append("Evidence ID: ").append(evidence.getId()).append('\n');
        report.append("Case ID: ").append(evidence.getInvestigationCase().getCaseId()).append('\n');
        report.append("Case Title: ").append(evidence.getInvestigationCase().getTitle()).append('\n');
        report.append("Original Filename: ").append(evidence.getOriginalFilename()).append('\n');
        report.append("MIME Type: ").append(evidence.getMimeType()).append('\n');
        report.append("File Size: ").append(evidence.getFileSize()).append(" bytes\n");
        report.append("SHA-256: ").append(evidence.getSha256Hash()).append('\n');
        report.append("Status: ").append(evidence.getStatus()).append('\n');
        report.append("Uploaded By: ").append(evidence.getUploadedBy().getUsername()).append('\n');
        report.append("Uploaded At: ").append(evidence.getUploadedAt().format(formatter)).append("\n");
        report.append("Description: ").append(evidence.getDescription() == null ? "" : evidence.getDescription()).append("\n\n");

        report.append("VERIFICATION HISTORY\n");
        report.append("------------------------------------------------------------\n");

        if (history.isEmpty()) {
            report.append("No verification attempts recorded.\n");
        } else {
            for (EvidenceVerification v : history) {
                report.append("Verification #").append(v.getId()).append('\n');
                report.append("Result: ").append(v.getResult()).append('\n');
                report.append("Expected SHA-256: ").append(v.getExpectedHash()).append('\n');
                report.append("Calculated SHA-256: ").append(v.getCalculatedHash()).append('\n');
                report.append("Verified By: ").append(v.getVerifiedBy().getUsername()).append('\n');
                report.append("Verified At: ").append(v.getVerifiedAt().format(formatter)).append("\n\n");
            }
        }

        report.append("CHAIN OF CUSTODY / ACCESS EVENTS\n");
        report.append("------------------------------------------------------------\n");
        if (timeline.isEmpty()) {
            report.append("No evidence audit events recorded.\n");
        } else {
            for (var event : timeline) {
                report.append(event.getTimestamp().format(formatter)).append(" | ")
                        .append(event.getAction()).append(" | ")
                        .append(event.getResult()).append(" | user=")
                        .append(event.getActorUsername() == null ? "system" : event.getActorUsername()).append("\n");
            }
        }
        report.append("\nReport generated by: ").append(authentication.getName()).append('\n');
        report.append("Report generated at: ").append(java.time.LocalDateTime.now().format(formatter)).append('\n');
        report.append("\nNote: SHA-256 verifies file-content integrity; it does not by itself establish legal authenticity or complete chain of custody.\n");

        byte[] body = report.toString().getBytes(StandardCharsets.UTF_8);

        return ResponseEntity.ok()
                .contentType(MediaType.TEXT_PLAIN)
                .contentLength(body.length)
                .header(HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=\"evidence-report-" + evidence.getId() + ".txt\"")
                .body(body);
    }
}
